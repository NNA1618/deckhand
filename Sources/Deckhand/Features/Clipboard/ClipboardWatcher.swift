import AppKit

/// Polls NSPasteboard.changeCount and stores new content in ClipboardStore.
@MainActor
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()

    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    private let store = ClipboardStore.shared

    private init() {}

    func start() {
        stop()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        RunLoop.main.add(timer!, forMode: .common)
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func tick() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        capture(pb: pb)
    }

    /// Password managers mark their copies with these types (nspasteboard.org convention).
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private func capture(pb: NSPasteboard) {
        let source = currentSource()
        let settings = Settings.shared

        let types = Set((pb.types ?? []).map(\.rawValue))
        if !settings.savePasswordsToHistory && !types.isDisjoint(with: Self.concealedTypes) {
            Log.info("clipboard: concealed item skipped")
            return
        }
        if let app = source.bundleId, settings.excludedApps.contains(app) { return }

        // Priority: file > image > string
        if let urls = pb.readObjects(forClasses: [NSURL.self]) as? [URL], let first = urls.first {
            for url in urls {
                store.insert(kind: .file, fileURL: url, source: source)
            }
            // A single image file is also stored as an image
            if urls.count == 1, let data = try? Data(contentsOf: first),
               NSImage(data: data) != nil {
                store.insert(kind: .image, imageData: data, source: source)
            }
            return
        }

        if let img = NSImage(pasteboard: pb),
           let tiff = img.tiffRepresentation,
           let bitmap = NSBitmapImageRep(data: tiff),
           let png = bitmap.representation(using: .png, properties: [:]) {
            store.insert(kind: .image, imageData: png, source: source)
            return
        }

        if let str = pb.string(forType: .string), !str.isEmpty {
            if str.count < 1 { return }
            store.insert(kind: .text, text: str, source: source)
            return
        }
    }

    private func currentSource() -> (bundleId: String?, name: String?) {
        guard let app = NSWorkspace.shared.frontmostApplication else { return (nil, nil) }
        return (app.bundleIdentifier, app.localizedName)
    }
}
